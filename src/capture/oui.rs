    #[test]
    fn knows_apple() {
        assert_eq!(lookup(&[0xb8, 0x53, 0xac, 0x12, 0x34, 0x56]), Some("Apple"));
        assert_eq!(lookup(&[0xf0, 0xdb, 0xe2, 0, 0, 0]), Some("Apple"));
    }

    #[test]
    fn knows_raspberry_pi() {
        assert_eq!(lookup(&[0xb8, 0x27, 0xeb, 0, 0, 0]), Some("Raspberry Pi"));
    }

    #[test]
    fn unknown_returns_none() {
        assert_eq!(lookup(&[0xff, 0xff, 0xff, 0, 0, 0]), None);
    }
