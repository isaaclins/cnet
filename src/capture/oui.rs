//! Vendor lookup from the first 3 bytes of a MAC address (OUI).
//!
//! Not comprehensive — a curated subset of common consumer / networking vendors.
//! For an unmatched OUI we return None; the device just shows without a vendor tag.

use std::collections::HashMap;
use std::sync::OnceLock;

use super::model::MacAddr;

pub fn lookup(mac: &MacAddr) -> Option<&'static str> {
    static MAP: OnceLock<HashMap<u32, &'static str>> = OnceLock::new();
    let map = MAP.get_or_init(|| {
        let mut m = HashMap::with_capacity(TABLE.len());
        for (oui, name) in TABLE {
            m.insert(*oui, *name);
        }
        m
    });
    let oui = ((mac[0] as u32) << 16) | ((mac[1] as u32) << 8) | (mac[2] as u32);
    map.get(&oui).copied()
}

